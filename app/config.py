from pathlib import Path

from pydantic_settings import BaseSettings

SERVER_DIR = Path(__file__).resolve().parent.parent


class Settings(BaseSettings):
    database_url: str = "postgresql+psycopg://sayr:sayr@localhost:5432/sayr"
    media_dir: Path = SERVER_DIR / "media"
    admin_username: str = "admin"

    # Без значений по умолчанию — приложение падает на старте, пока их не задали.
    # Это намеренно: с известным secret_key админку открывают подделанной cookie
    # `session={"admin": true}`, минуя форму входа. Дефолт, лежащий в открытом
    # репозитории, означал бы открытую панель на любом сервере, где забыли .env.
    admin_password: str
    secret_key: str

    # Cookie админки только по HTTPS. Локально по http поставь false в .env
    admin_cookie_secure: bool = True

    # Пароль страницы проверки сезонов (/seasons/review). Пусто — пускает
    # по админскому: так страница работает сразу после выката. Задаётся,
    # когда проверку отдают кому-то из клуба, — чтобы вместе с ней
    # не отдавать всю админку
    review_password: str = ""

    # Игра «когда сюда идти» (/seasons). Выключена: страница отвечает «игра
    # закрыта», колода пустая, ответы не принимаются; проверка собранного
    # (/seasons/review) работает как раньше. Открыть снова —
    # SAYR_SEASONS_OPEN=1 в .env и перезапуск службы
    seasons_open: bool = False

    # Пусто — CORS выключен. Нативным клиентам он не нужен, список понадобится,
    # только если появится веб-морда: SAYR_CORS_ORIGINS=["https://sayr.uz"]
    cors_origins: list[str] = []

    # Адреса магазинов для лендинга. Пока пусты — страница честно пишет
    # «скоро»: она поднимается раньше, чем приложения проходят ревью,
    # а ссылка в никуда хуже отсутствующей
    app_store_url: str = ""
    play_store_url: str = ""

    weather_cache_ttl_sec: int = 30 * 60

    # Сколько дней держим сырые события статистики. Дневные агрегаты живут
    # вечно, стирается только сырьё. Тридцать, а не больше: столько же
    # обещано на /privacy для технических журналов, и два разных срока
    # означали бы, что в одном из мест мы врём
    stats_retention_days: int = 30
    # Считать ли отладочные сборки (суффикс -debug в X-Sayr-App). На бою
    # выключено: эмулятор и симулятор ходят на боевой сервер, и каждая
    # проверка ложилась в статистику живым человеком. Включается локально,
    # чтобы проверять свою же работу против своего же сервера
    stats_count_debug: bool = False

    # Вход по номеру телефона. Пустой токен — канал выключен, и ручка входа
    # честно отвечает «вход недоступен», а не падает: сервер должен
    # подниматься и без шлюза — локально, в тестах и на бою до того, как
    # владелец пополнит счёт в Fragment
    tg_gateway_token: str = ""
    # Проверенный канал-отправитель в телеграме. Пусто — код придёт
    # от служебного аккаунта шлюза, это нормальный режим
    tg_gateway_sender: str = ""
    # Куда шлюз шлёт отчёт о доставке. Пусто — отчётов нет, и о том, что код
    # не дошёл, мы узнаем только по истечении времени жизни
    tg_gateway_callback_url: str = ""
    # Ключ в адресе отчёта о доставке. Пусто — ручка отчётов выключена:
    # открытая наружу, она позволяла бы гасить чужие заявки
    tg_gateway_callback_key: str = ""
    # Код живёт пять минут: меньше — человек не успеет переключиться
    # в телеграм и обратно, больше — заявка висит без дела
    login_code_ttl_sec: int = 300
    login_code_length: int = 6
    # Пока тикает, кнопка «Отправить ещё раз» спит: каждая отправка платная
    login_resend_after_sec: int = 60
    # Попыток ввода на заявку. Три — столько же, сколько даёт сам шлюз
    login_max_attempts: int = 3
    # Потолок платных кодов за сутки на всех. Лимиты на номер, устройство
    # и адрес держат одного человека, а скрипт со многих адресов и со
    # случайными номерами упирается только в него — иначе он выбрал бы
    # весь счёт шлюза. Сверх потолка вход отвечает «пока недоступен»;
    # 0 — без потолка
    login_codes_per_day: int = 500
    # Потолок обращений к шлюзу за сутки на всех, вместе с неотправленными.
    # Номер без телеграма в платный потолок не идёт, но шлюз о нём всё равно
    # спрашивают, а заявка ложится в таблицу: скрипт со случайными номерами
    # раздувал бы её без меры, и каждый счёт лимита читал бы всё больше.
    # Пятикратный запас над платным — живым людям не мешает; 0 — без потолка
    login_gateway_calls_per_day: int = 2500
    #: Номер для проверяющих магазинов: код к нему в телеграм не уходит,
    #: а сравнивается с login_test_code. Пусто — обхода нет. На бою задаётся
    #: в .env и сообщается только в анкетах App Store и Play
    login_test_phone: str = ""
    login_test_code: str = ""

    # Пуши. Пустой путь — платформа не настроена: планировщик пропустит её
    # устройства и запишет это в last_error объявления, а не упадёт целиком.
    # APNs — ключ .p8 из Apple Developer и его Key ID; тема — bundle id
    apns_key_path: Path | None = None
    apns_key_id: str = ""
    apns_team_id: str = "Z39Z5TJZCG"
    apns_topic: str = "uz.sayr.ios"
    # Песочница APNs принимает токены только debug-сборок из Xcode;
    # TestFlight и App Store ходят в боевой
    apns_sandbox: bool = False
    # FCM — сервисный ключ проекта Firebase (JSON)
    fcm_service_account_path: Path | None = None

    # Попутчики (спека docs/superpowers/specs/2026-09-27-companions-design.md).
    # Выключены, пока не готовы Sayr Admin и политика: ручки комнат отвечают
    # 404, а приложения узнают об этом из features.rooms в /app/update и прячут
    # блок «Попутчики» — сборки уходят в магазины раньше, чем включаемся
    rooms_open: bool = False
    #: Адрес сайта для ссылок, которые сервер отдаёт сам: приглашение
    #: в комнату https://sayr.info/r/…
    public_url: str = "https://sayr.info"

    # Sayr Admin — аккаунт Telegram, который заводит группы комнат (служба
    # sayr-tg, python -m app.tg.worker). Ключи с my.telegram.org и строка
    # сессии из python -m app.tg.login. Пусто — служба ждёт входа и ничего
    # не делает, комнаты живут без групп
    tg_api_id: int = 0
    tg_api_hash: str = ""
    tg_session: str = ""
    #: Не больше стольких новых групп в час: аккаунт, который создаёт группы
    #: пачками, Telegram помечает как спамера
    tg_groups_per_hour: int = 10

    # «Универсальные» ссылки sayr.info/p/… и /r/…: сайт подтверждает, что
    # открывать их вправе наше приложение. iOS — «TEAMID.bundle id»; Android —
    # пакет и SHA-256 сертификатов подписи через запятую: ключ загрузки
    # (локальные релизные сборки) и ключи подписи Play из Play Console.
    # Отпечатки не секрет — их и так раздаёт assetlinks.json
    ios_app_ids: str = "Z39Z5TJZCG.uz.sayr.ios"
    android_package: str = "uz.sayr.android"
    android_cert_sha256: str = (
        # ключ загрузки
        "8E:08:07:49:AA:43:7E:E7:87:8B:C4:13:91:5D:1F:15:"
        "C3:31:65:39:B5:05:E2:A8:F0:6C:CC:A3:7C:18:85:13,"
        # ключ подписи Play, классический — им подписаны сборки из магазина
        "09:8D:22:DD:88:12:BB:03:E2:DC:E9:65:E5:BC:FB:49:"
        "80:70:0F:EB:54:18:B0:18:3E:8B:9D:BC:35:11:28:99,"
        # и постквантовый из гибридной подписи Play: какой из двух сверит
        # система, зависит от версии Android — отдаём оба
        "E1:3A:97:56:F1:F9:20:8D:05:4C:00:CD:EA:E7:04:84:"
        "C3:63:1B:06:4B:9D:98:7E:E5:64:02:35:B3:E7:9B:A9"
    )
    #: iPhone, открывший /p/…, уводим в App Store (app_links.py). Включать,
    #: когда у людей сборка с «универсальными» ссылками: у старых версий ссылка
    #: не открывает приложение сама, и в магазин ушли бы те, у кого оно есть
    ios_store_redirect: bool = False

    model_config = {"env_file": SERVER_DIR / ".env", "env_prefix": "SAYR_"}


settings = Settings()

PHOTOS_DIR = settings.media_dir / "photos"
THUMBS_DIR = settings.media_dir / "thumbs"
GPX_DIR = settings.media_dir / "gpx"
# Фото из анкеты. Отдельно от photos: снимки мест ставит владелец, а это
# чужие лица, и правила у них разные — удаление аккаунта уносит файл сразу,
# без корзины
AVATARS_DIR = settings.media_dir / "avatars"

# Файлы, приложенные к заявкам с формы /report. Лежат внутри media_dir,
# потому что это единственный каталог на томе docker: всё остальное внутри
# контейнера стирается пересборкой, а фотография несошедшегося поворота
# нужна ровно тогда, когда до заявки дошли руки, — месяцем позже.
#
# При этом наружу они НЕ отдаются: в main.py под /media смонтированы три
# каталога поимённо, а не media_dir целиком. Это чужие файлы, присланные
# незнакомыми людьми: там бывает и лишнее в кадре, и просто мусор, и
# публичная ссылка на sayr.info превратила бы форму в файлохостинг.
# Владельцу они открываются через админку, по сессии
REPORTS_DIR = settings.media_dir / "reports"

# Куда уезжают снимки, удалённые из админки. Внутри media_dir — рядом
# с photos, из которого их и переносят, и это обязательное условие,
# а не вкусовщина.
#
# Раньше корзина лежала в SERVER_DIR, «подальше от раздаваемого». Но юнит
# идёт с ProtectSystem=strict и ReadWritePaths=<...>/media, а systemd
# выполняет ReadWritePaths bind-монтированием: внутри службы media —
# отдельная точка монтирования. rename() через границу монтирования
# отказывает с EXDEV, даже когда файловая система под ней одна и та же.
# С 24 по 26 августа так молча потерялись 55 снимков: строки из базы
# ушли, файлы остались лежать в photos и открываться по прямой ссылке.
#
# Наружу каталог при этом не выходит: в main.py под /media смонтированы
# три подкаталога поимённо (photos, thumbs, gpx), а не media_dir целиком.
# Той же защитой закрыт и REPORTS_DIR выше.
#
# Не удаляем совсем, потому что цена ошибки несимметрична: лишний файл
# на диске — ничто, а промах по кнопке стоит снимка, который искали
# вручную по выгрузке форума и второй раз можем не найти.
DELETED_PHOTOS_DIR = settings.media_dir / "deleted-photos"

# StaticFiles и FileSystemStorage требуют существующих директорий уже на импорте
for _d in (PHOTOS_DIR, THUMBS_DIR, GPX_DIR, REPORTS_DIR, AVATARS_DIR):
    _d.mkdir(parents=True, exist_ok=True)
