"""Промахи паролем на /admin и /seasons/review: счётчик и паузы.

Обе формы открыты всему интернету, и до этого счётчика пароль к ним можно
было перебирать без ограничений — скрипт делал бы сотни попыток в минуту.
Теперь несколько промахов подряд прощаются (опечатка, не та раскладка),
а дальше вход с этого адреса запирается, и каждая следующая пауза вдвое
длиннее прежней.

Счётчик ведётся по паролю, а не по странице: пока у проверки сезонов нет
своего пароля, она пускает по админскому (seasons_review._password), и
перебор через неё — тот же перебор админки. Поэтому обе формы пишут промахи
в одну дверь ADMIN, и отдельная дверь REVIEW появляется только вместе
с отдельным паролем. Иначе знающий пароль проверки — кто-то из клуба —
сбрасывал бы удачным входом счётчик промахов по админскому.

Счётчики живут в памяти процесса, как у формы обращений и входа по номеру:
перезапуск их обнуляет, воркеров два — настоящий предел вдвое мягче. Этого
хватает: держим скрипт, а не человека. Владельца пауза не запирает насовсем:
она не длиннее MAX_LOCK_SEC и касается только одного адреса, а если очень
надо войти прямо сейчас — перезапуск sayr.service снимает все паузы разом.
"""

import hashlib
import hmac
import math
import time

from starlette.requests import Request

from .client_ip import limit_key
from .config import settings

ADMIN = "admin"
REVIEW = "review"

#: Столько промахов подряд прощаем без паузы
FREE_FAILURES = 5
#: Первая пауза — минута, дальше вдвое: две, четыре, восемь… до четверти часа.
#: Потолок нужен владельцу: за общим адресом сотового оператора сидит
#: пол-города, и перебор соседа не должен запирать его на весь вечер
FIRST_LOCK_SEC = 60
MAX_LOCK_SEC = 15 * 60
#: Сутки без промахов — адрес забыт
FORGET_SEC = 24 * 3600

#: Больше адресов не помним. Запись заводит каждый промах с нового адреса,
#: а у кого своя /48, у того таких /64 десятки тысяч — словарь рос бы
#: без края. Вытесняются те, кто промахивался давнее всех
MAX_SLOTS = 10_000

#: «дверь:адрес» → (промахов подряд, время последнего, заперто до).
#: Ключи идут по времени последнего промаха: failed() переставляет запись
#: в конец, так что забытые и вытесняемые всегда лежат в начале
_FAILS: dict[str, tuple[int, float, float]] = {}


def client_key(request: Request) -> str:
    """Адрес, по которому считаем промахи: тот же ключ, что у остальных
    счётчиков (IPv6 — сетью /64, см. client_ip).

    Прокси с другого адреса, не с 127.0.0.1, надо назвать uvicorn
    в --forwarded-allow-ips (так сделано в compose.prod.yml): иначе для
    счётчика все клиенты — один адрес прокси, и шесть чужих промахов
    запирают вход всем, владельцу тоже.
    """
    return limit_key(request)


def _slot(door: str, request: Request) -> str:
    return f"{door}:{client_key(request)}"


def _forget_stale(now: float) -> None:
    """Снимает с начала словаря адреса, молчавшие сутки.

    Раньше каждая попытка входа перебирала словарь целиком — на сотнях
    тысяч адресов это миллисекунды, на которые встаёт весь воркер. Ключи
    идут по времени промаха, поэтому хватает дойти до первого свежего.
    Пауза у снятых давно кончилась: она короче суток.
    """
    while _FAILS:
        oldest = next(iter(_FAILS))
        if now - _FAILS[oldest][1] <= FORGET_SEC:
            return
        del _FAILS[oldest]


def locked_for(door: str, request: Request) -> int:
    """Сколько секунд ещё заперто; 0 — пароль можно проверять.

    Пока заперто, пароль не проверяется вовсе, даже верный: иначе перебор
    просто шёл бы дальше, а пауза лишь меняла бы текст ответа на промахах.

    Между этой проверкой и failed()/passed() у вызывающего не должно быть
    ни одного await: иначе залп параллельных запросов весь проходит
    проверку раньше, чем первый из них запишет промах.
    """
    now = time.monotonic()
    _forget_stale(now)
    entry = _FAILS.get(_slot(door, request))
    if entry is None:
        return 0
    return max(0, math.ceil(entry[2] - now))


def failed(door: str, request: Request) -> None:
    """Промах. После FREE_FAILURES подряд — пауза, каждая вдвое длиннее"""
    now = time.monotonic()
    _forget_stale(now)
    slot = _slot(door, request)
    # pop, а не get: запись встаёт в конец словаря, к самым свежим
    count = _FAILS.pop(slot, (0, 0.0, 0.0))[0] + 1
    until = now
    if count > FREE_FAILURES:
        # Степень ограничена, чтобы число не росло без края: потолок
        # всё равно наступает на пятой паузе
        until = now + min(MAX_LOCK_SEC, FIRST_LOCK_SEC * 2 ** min(count - FREE_FAILURES - 1, 10))
    _FAILS[slot] = (count, now, until)
    while len(_FAILS) > MAX_SLOTS:
        del _FAILS[next(iter(_FAILS))]


def passed(door: str, request: Request) -> None:
    """Верный пароль — прежние промахи с этого адреса прощены"""
    _FAILS.pop(_slot(door, request), None)


def fingerprint(password: str) -> str:
    """Отпечаток пароля — его кладём в cookie входа и сверяем на каждом запросе.

    Смена пароля меняет отпечаток, и все открытые входы разом становятся
    недействительными: раньше cookie админки переживала смену
    SAYR_ADMIN_PASSWORD и открывала панель ещё две недели.

    HMAC на secret_key, а не голый sha256: cookie подписана, но не
    зашифрована — base64 читает всякий, у кого она оказалась, и простой
    хеш пароля можно было бы перебирать офлайн без всяких пауз.
    """
    return hmac.new(
        settings.secret_key.encode(), password.encode(), hashlib.sha256
    ).hexdigest()[:32]
