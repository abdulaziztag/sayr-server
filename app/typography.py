"""Узбекские oʻ, gʻ и тутук — в знаках, которые шрифт рисует слитно.

По орфографии oʻ и gʻ пишутся через U+02BB «ʻ», тутук — через U+02BC «ʼ»,
и так текст лежит в базе и в исходниках. Но в IBM Plex, которым набраны
приложения и страницы, эти знаки шире самой буквы «o» (600 из 1000 против
560) и стоят с большим отступом слева: на экране выходит «O ʻ zbekiston».
Кавычки U+2018 «‘» и U+2019 «’» в том же шрифте узкие (273), и через них
oʻ и gʻ пишет большинство узбекских сайтов (kun.uz, gov.uz).

Замена делается на выходе, и только там: база и исходники остаются
в правильной орфографии, а сменится шрифт — хватит убрать одну функцию.
В ресурсах приложений (values-uz, Localizable.xcstrings) узкие знаки
стоят сразу: эти строки через сервер не идут.
"""

#: Знак орфографии → узкая кавычка того же рисунка
_DISPLAY = str.maketrans({"\u02bb": "\u2018", "\u02bc": "\u2019"})

#: Чем набирают узбекский апостроф: оба знака орфографии, обе кавычки,
#: прямой апостроф и гравис
_APOSTROPHES = str.maketrans("", "", "\u02bb\u02bc\u2018\u2019'`")


def uz_display(text: str) -> str:
    """«Oʻzbekiston» → «O‘zbekiston», «maʼlumot» → «ma’lumot».

    Текст без этих знаков возвращается как был, поэтому звать можно на всём,
    что уходит на экран: на русской странице меняется только ссылка
    «Oʻzbekcha», в русском описании — цитата «узб. Beshtor choʻqqisi».
    """
    return text.translate(_DISPLAY)


def fold_apostrophes(text: str) -> str:
    """Без апострофов вовсе: «Koʻl», «Ko‘l», «Ko'l» и «Kol» — одно слово.

    Для сверки набранного человеком с тем, что стоит на экране: клавиатура
    даёт любой из этих знаков, а на странице уже «‘».
    """
    return text.translate(_APOSTROPHES)
